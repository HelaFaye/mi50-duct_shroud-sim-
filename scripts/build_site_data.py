#!/usr/bin/env python3
"""Generate site/js/fan_data.js from the repository's validated fan datasets.

The browser editor cannot read files outside site/, so the solver-ready fan
curves and the P9 Max electrical table are embedded as a generated ES module.
Each entry records its source path and SHA-256 so the embedded data stays
traceable. Curves are loaded through the same validators the Python solvers
use; nothing is smoothed, rescaled, or repaired.

    python3 scripts/build_site_data.py          # write the module
    python3 scripts/build_site_data.py --check  # fail if it is out of date
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from analysis.fan_electrical import load_fan_electrical_dataset  # noqa: E402
from analysis.fan_operating_point import FanCurve  # noqa: E402

OUTPUT = ROOT / "site" / "js" / "fan_data.js"

FANS = [
    {
        "id": "arctic_p9_max_mfr",
        "label": "ARCTIC P9 Max @ 4300 RPM (manufacturer CFD table)",
        "frame_mm": 92,
        "rpm": 4300,
        "path": "data/fan_curves/arctic_p9_max_4300rpm_manufacturer_cfd.csv",
        "provenance": "Manufacturer CFD workbook table; no published pointwise uncertainty. See docs/ARCTIC_P9_MAX_CURVE_PROVENANCE.md.",
        "electrical": {"path": "data/fan_curves/arctic_p9_max_pwm_electrical.csv", "voltage_v": 12.0},
    },
    {
        "id": "arctic_p9_max_digitized",
        "label": "ARCTIC P9 Max @ 4300 RPM (historical chart digitization)",
        "frame_mm": 92,
        "rpm": 4300,
        "path": "data/fan_curves/arctic_p9_max_4300rpm_digitized.csv",
        "provenance": "Approximate manual digitization of the published chart; kept for comparison.",
        "electrical": {"path": "data/fan_curves/arctic_p9_max_pwm_electrical.csv", "voltage_v": 12.0},
    },
    {
        "id": "noctua_nf_a14_1500",
        "label": "Noctua NF-A14 PWM @ 1500 RPM (manufacturer)",
        "frame_mm": 140,
        "rpm": 1500,
        "path": "data/fan_curves/noctua_nf_a14_pwm_1500rpm_manufacturer.csv",
        "provenance": "Manufacturer five-point curve converted from m³/h. See docs/NOCTUA_FAN_DATA_PROVENANCE.md.",
        "electrical": None,
    },
]


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build() -> str:
    fans = []
    for spec in FANS:
        path = ROOT / spec["path"]
        curve = FanCurve.from_csv(path)
        entry = {
            "id": spec["id"],
            "label": spec["label"],
            "frame_mm": spec["frame_mm"],
            "rpm": spec["rpm"],
            "source": spec["path"],
            "sha256": _sha256(path),
            "provenance": spec["provenance"],
            "points": [[flow, pressure] for flow, pressure in curve.points],
            "electrical": None,
        }
        if spec["electrical"]:
            epath = ROOT / spec["electrical"]["path"]
            dataset = load_fan_electrical_dataset(epath)
            table = dataset.curves[spec["electrical"]["voltage_v"]]
            entry["electrical"] = {
                "source": spec["electrical"]["path"],
                "sha256": dataset.source_sha256,
                "voltage_v": spec["electrical"]["voltage_v"],
                "points": [
                    {"rpm": p.fan_speed_rpm, "current_a": p.current_a, "power_w": p.power_w}
                    for p in table.points
                ],
            }
        fans.append(entry)
    body = json.dumps(fans, indent=2, sort_keys=True, allow_nan=False)
    return (
        "// GENERATED by scripts/build_site_data.py — do not edit by hand.\n"
        "// Regenerate after changing any source CSV listed below.\n"
        f"export const FANS = {body};\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated file is stale")
    args = parser.parse_args(argv)
    content = build()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run scripts/build_site_data.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
